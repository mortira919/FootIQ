"""Фильтр мата, оскорблений и языка вражды для имён игроков и названий лиг (Apple 1.2, Google UGC),
а также для выдачи ИИ-тренера (Google AI-Generated Content).

Как обходят фильтры и что с этим делаем:
- латиница и цифры вместо кириллицы (xyй, 6ля, п1зда) → приводим двойники к кириллице;
- пробелы, точки, дефисы между буквами (х у й, х.у.й) → склеиваем подряд идущие одиночные буквы
  и отдельно проверяем текст без разделителей;
- повтор букв (хуууй) → схлопываем повторы;
- транслит (blyad, nahui) → отдельный список для латинских слов.

Корни подобраны так, чтобы не задевать обычные слова: «тебе», «себя», «корабля», «рубля», «оскорбление»,
«Педро», «мудрый», «жидкость», «хулиган», «застраховать». Эти слова закреплены тестом.
"""

import re
import unicodedata

# Двойники: латиница, цифры и символы, похожие на кириллические буквы.
HOMOGLYPHS = str.maketrans(
    {
        "a": "а", "b": "в", "c": "с", "e": "е", "h": "н", "k": "к", "m": "м", "o": "о", "p": "р",
        "t": "т", "x": "х", "y": "у", "z": "з", "u": "и", "n": "п", "r": "г", "g": "д", "d": "д", "i": "і",
        "0": "о", "3": "з", "4": "ч", "6": "б", "8": "в", "@": "а", "$": "с", "ё": "е", "1": "і", "!": "і", "|": "і",
    }
)

# Фрагменты обычных слов, где корень входит законно. Их вырезают из токена перед проверкой,
# поэтому «оскорбление» проходит, а склейка «тебехуй» нет.
SAFE = re.compile(
    r"страху|оскорбл|употребл|истребл|корабл|рубл|гребл|скребл|колебл|хулига|хулит|хула|"
    r"мудр|жидк|жидел|педал|педаг|педиатр|сукно|сукон|мандарин|мандат|хлеб|бляха|блях"
)

# Корни, которые ищем внутри любого токена (после нормализации).
ANYWHERE = [
    r"ху[йяеию]",            # хуй, хуя, хуе(ть), хуи, хую, нахуй, похуй
    r"пизд",                 # пизда и производные
    r"бляд", r"блят",        # блядь, блять
    r"ебан", r"ебат", r"ебал", r"ебло", r"ебуч", r"ебн", r"ебыр", r"ебл[аои]",
    r"[её]баный", r"[её]бнут",
    r"уеб", r"заеб", r"наеб", r"выеб", r"отъеб", r"съеб", r"разъеб", r"доеб", r"проеб", r"переб[её]б", r"поеб",
    r"долб[ао][её]б",
    r"мудак", r"мудил", r"мудо[зх]", r"мудач",
    r"пид[оа]?р", r"пед[оа]р", r"педераст", r"педик",
    r"залуп", r"гандон", r"гондон", r"дроч", r"шлюх", r"шалав", r"курв",
    r"ублюд", r"мраз[ьи]", r"говн", r"гавн", r"сучк", r"сучар", r"сукин",
    r"дебил", r"дибил", r"даун[ыа]?$", r"идиот", r"дегенерат", r"чмо",
    r"ниг+ер", r"нигга", r"хач[иуе]?$", r"чурк", r"жид[ыаоу]?$", r"жидов", r"хохл", r"москал", r"пиндос",
    r"гитлер", r"нацик", r"зигхайл",
]
# Слова, которые запрещены только целиком (иначе слишком много ложных срабатываний).
WHOLE = {"сука", "суки", "суку", "суке", "сукой", "бля", "тварь", "твари", "лох", "лохи", "чмо", "хер", "нахер", "похер"}

# Латиница и транслит: проверяем по исходному тексту в нижнем регистре, без замены двойников.
# Повторы букв схлопываются до проверки, поэтому корни записаны с одинарными буквами (nigger → niger).
LATIN = [
    r"fuck", r"fck", r"shit", r"bitch", r"cunt", r"nig[e3]r", r"niga", r"fag[o0]t", r"whore", r"slut", r"ashole",
    r"motherf", r"blya", r"bljad", r"pizd", r"pidor", r"pidar", r"nahu[iy]", r"xyu", r"huy", r"hui$", r"ebat",
    r"eblan", r"suka$", r"mudak", r"gandon", r"hitler", r"nazi",
]

# Для выдачи ИИ-тренера: опасные темы, которых не должно быть в разборе футбольного эпизода.
HARMFUL = [
    r"убе?й", r"убива", r"суицид", r"самоуби", r"покончи", r"режь", r"вскрой", r"наркот", r"героин", r"кокаин",
    r"оружи", r"взорв", r"бомб", r"теракт", r"изнасил", r"kill yourself", r"suicide",
]

_ANY = re.compile("|".join(ANYWHERE))
_LATIN = re.compile("|".join(LATIN))
_HARMFUL = re.compile("|".join(HARMFUL))
_SPLIT = re.compile(r"[^0-9a-zа-яёіі@$!|]+")


def _plain(text: str) -> str:
    # NFKC оставляет «й» и «ё» целыми. Отдельные знаки ударения (U+0301) и невидимые символы
    # нулевой ширины, которыми разбивают слова, вырезаем.
    text = unicodedata.normalize("NFKC", text.lower())
    return "".join(ch for ch in text if unicodedata.category(ch) not in ("Mn", "Me", "Cf"))


def _cyr(token: str) -> str:
    return _collapse(token.translate(HOMOGLYPHS).replace("і", "и"))


def _tokens(text: str) -> list[str]:
    raw = [token for token in _SPLIT.split(text) if token]
    tokens, singles = [], []
    for token in raw:
        if len(token) == 1:
            singles.append(token)
            continue
        if len(singles) > 1:
            tokens.append("".join(singles))
        singles = []
        tokens.append(token)
    if len(singles) > 1:
        tokens.append("".join(singles))
    return tokens + [token for token in raw if len(token) == 1]


def _collapse(token: str) -> str:
    return re.sub(r"(.)\1+", r"\1", token)


def _bad_token(token: str) -> bool:
    return token in WHOLE or bool(_ANY.search(SAFE.sub("_", token)))


def is_offensive(text: str) -> bool:
    plain = _plain(text)
    for token in _tokens(plain):
        if _LATIN.search(_collapse(token)) or _bad_token(_cyr(token)):
            return True
    # «пи-зда», «ху й»: текст целиком без разделителей, только для однозначных корней.
    glued = SAFE.sub("_", _cyr("".join(_SPLIT.split(plain))))
    return bool(re.search(r"ху[йяи]|пизд|бляд|еба[нтл]|пидор|пидар|мудак|залуп|гандон|гондон|шлюх", glued))


def is_harmful(text: str) -> bool:
    plain = _plain(text)
    return bool(_HARMFUL.search(plain)) or is_offensive(text)
